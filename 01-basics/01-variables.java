class Variables {
    public static void main(String[] args) {

        String name = "Rafik";
        int age = 21;
        double cgpa = 3.85;
        char grade = 'A';
        boolean student = true;

        System.out.println(name);
        System.out.println(age);
        System.out.println(cgpa);
        System.out.println(grade);
        System.out.println(student);

        age = 22;

        System.out.println(age);
    }
}