class TypeCasting {
    public static void main(String[] args) {

        double price = 99.99;
        int newPrice = (int) price;

        int marks = 85;
        double newMarks = marks;

        System.out.println(price);
        System.out.println(newPrice);

        System.out.println(marks);
        System.out.println(newMarks);
    }
}